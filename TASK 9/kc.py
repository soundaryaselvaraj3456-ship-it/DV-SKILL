df.loc[df["bedrooms"] <= 0, "bedrooms"] = None
df.loc[df["bathrooms"] <= 0, "bathrooms"] = None

df.dropna(subset=[
    "price", "bedrooms", "bathrooms",
    "sqft_living", "sqft_lot", "yr_built", "date"
], inplace=True)

df = df[
    (df["price"] > 0) &
    (df["sqft_living"] > 0) &
    (df["sqft_lot"] > 0)
].copy()

df["date"] = pd.to_datetime(
    df["date"], format="%Y%m%dT%H%M%S", errors="coerce"
)
df.dropna(subset=["date"], inplace=True)

df["sales_year"] = df["date"].dt.year

df["property_age"] = df["sales_year"] - df["yr_built"]

df["is_renovated"] = (df["yr_renovated"] > 0).astype(int)

df["years_since_renovation"] = (
    df["sales_year"] - df["yr_renovated"]
).where(df["yr_renovated"] > 0)

df.loc[df["property_age"] < 0, "property_age"] = None

df.loc[
    (df["yr_renovated"] > df["sales_year"]) |
    ((df["yr_renovated"] > 0) &
     (df["yr_renovated"] < df["yr_built"])),
    "years_since_renovation"
] = None

df["price_per_sqft_living"] = df["price"] / df["sqft_living"]
df["price_per_sqft_lot"] = df["price"] / df["sqft_lot"]

for col in ["price_per_sqft_living", "price_per_sqft_lot"]:
    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)
    IQR = Q3 - Q1

    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    df[col + "_outlier"] = (
        (df[col] < lower_bound) |
        (df[col] > upper_bound)
    )

    print("\nFeature:", col)
    print("Lower Bound:", lower_bound)
    print("Upper Bound:", upper_bound)
    print("Outliers:", df[col + "_outlier"].sum())

plt.figure(figsize=(12, 5))

